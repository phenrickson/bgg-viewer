  .frame:hover img { border-color: var(--primary); }

  /* One capture per theme; mode-watcher puts `.dark` on <html>. */
  img.dark { display: none; }
  :global(.dark) img.light { display: none; }
  :global(.dark) img.dark { display: block; }
</style>
